"""
models.py
Core data structures and cryptographic primitives for TransplantChain.
Implements SECP256k1 ECDSA signatures, canonical SHA-256 hashing,
binary Merkle trees, and Proof-of-Work block structures.
"""
import hashlib
import json
import time
from ecdsa import SigningKey, VerifyingKey, SECP256k1


class Transaction:
    """Represents an atomic medical transaction on the TransplantChain:
    - REGISTER_ORGAN   : An OPO or donor hospital registers a harvested organ.
    - REGISTER_PATIENT : A transplant center registers a waitlisted patient.
    - ALLOCATE_ORGAN   : Matches an available organ to the highest-priority eligible recipient.
    """

    def __init__(self, tx_type, sender_pubkey, payload,
                 signature=None, timestamp=None, tx_id=None):
        self.tx_type = tx_type  # REGISTER_ORGAN, REGISTER_PATIENT, ALLOCATE_ORGAN
        self.sender_pubkey = sender_pubkey
        self.payload = payload  # Dict containing domain-specific medical data
        self.timestamp = timestamp if timestamp is not None else time.time()
        self.tx_id = tx_id if tx_id is not None else self.calculate_hash()
        self.signature = signature

    def calculate_hash(self):
        """Computes deterministic SHA-256 hash over canonical sorted JSON."""
        data = {
            "tx_type": self.tx_type,
            "sender_pubkey": self.sender_pubkey,
            "payload": self.payload,
            "timestamp": self.timestamp,
        }
        serialized = json.dumps(data, sort_keys=True).encode("utf-8")
        return hashlib.sha256(serialized).hexdigest()

    def sign_transaction(self, private_key_hex):
        """Signs the tx_id using SECP256k1 ECDSA private key."""
        sk = SigningKey.from_string(bytes.fromhex(private_key_hex), curve=SECP256k1)
        self.signature = sk.sign(self.tx_id.encode("utf-8")).hex()

    def verify_signature(self):
        """Verifies that the signature was generated by the holder of sender_pubkey."""
        if not self.signature:
            return False
        try:
            vk = VerifyingKey.from_string(bytes.fromhex(self.sender_pubkey), curve=SECP256k1)
            return vk.verify(bytes.fromhex(self.signature), self.tx_id.encode("utf-8"))
        except Exception:
            return False

    def to_dict(self):
        """Serializes transaction to dict for HTTP transmission."""
        return {
            "tx_type": self.tx_type,
            "sender_pubkey": self.sender_pubkey,
            "payload": self.payload,
            "timestamp": self.timestamp,
            "tx_id": self.tx_id,
            "signature": self.signature,
        }

    @classmethod
    def from_dict(cls, data):
        """Reconstructs transaction from dict while preserving identical hash."""
        return cls(
            tx_type=data["tx_type"],
            sender_pubkey=data["sender_pubkey"],
            payload=data["payload"],
            signature=data.get("signature"),
            timestamp=data["timestamp"],
            tx_id=data["tx_id"],
        )


class MerkleTree:
    """Computes a balanced binary SHA-256 Merkle root from a list of transactions."""

    @staticmethod
    def compute_root(transactions):
        if not transactions:
            return hashlib.sha256(b"EMPTY_TRANSACTIONS").hexdigest()

        tx_hashes = [tx.tx_id for tx in transactions]
        while len(tx_hashes) > 1:
            if len(tx_hashes) % 2 != 0:
                tx_hashes.append(tx_hashes[-1])  # Duplicate last element if odd
            new_hashes = []
            for i in range(0, len(tx_hashes), 2):
                combined = tx_hashes[i] + tx_hashes[i + 1]
                parent = hashlib.sha256(combined.encode("utf-8")).hexdigest()
                new_hashes.append(parent)
            tx_hashes = new_hashes
        return tx_hashes[0]


class Block:
    """Represents a confirmed batch of transactions appended to the ledger."""

    def __init__(self, index, previous_hash, transactions, difficulty=2,
                 timestamp=None, nonce=None, block_hash=None):
        self.index = index
        self.timestamp = timestamp if timestamp is not None else time.time()
        self.previous_hash = previous_hash
        self.transactions = transactions
        self.merkle_root = MerkleTree.compute_root(transactions)
        self.difficulty = difficulty
        self.nonce = nonce
        self.hash = block_hash

        if self.nonce is None or self.hash is None:
            self.mine_block()

    def calculate_hash(self):
        """Computes SHA-256 hash of the block header."""
        header = {
            "index": self.index,
            "timestamp": self.timestamp,
            "previous_hash": self.previous_hash,
            "merkle_root": self.merkle_root,
            "difficulty": self.difficulty,
            "nonce": self.nonce,
        }
        serialized = json.dumps(header, sort_keys=True).encode("utf-8")
        return hashlib.sha256(serialized).hexdigest()

    def mine_block(self):
        """Proof-of-Work: searches for a nonce satisfying the difficulty target."""
        self.nonce = 0
        target = "0" * self.difficulty
        while True:
            candidate_hash = self.calculate_hash()
            if candidate_hash.startswith(target):
                self.hash = candidate_hash
                return
            self.nonce += 1

    def is_valid(self):
        """Performs self-integrity validation on header, Merkle root, PoW, and signatures."""
        if self.merkle_root != MerkleTree.compute_root(self.transactions):
            return False
        if self.calculate_hash() != self.hash:
            return False
        if not self.hash.startswith("0" * self.difficulty):
            return False
        for tx in self.transactions:
            if tx.sender_pubkey != "00" * 32 and not tx.verify_signature():
                return False
        return True

    def to_dict(self):
        return {
            "index": self.index,
            "timestamp": self.timestamp,
            "previous_hash": self.previous_hash,
            "merkle_root": self.merkle_root,
            "difficulty": self.difficulty,
            "nonce": self.nonce,
            "hash": self.hash,
            "transactions": [tx.to_dict() for tx in self.transactions],
        }

    @classmethod
    def from_dict(cls, data):
        txs = [Transaction.from_dict(t) for t in data["transactions"]]
        return cls(
            index=data["index"],
            previous_hash=data["previous_hash"],
            transactions=txs,
            difficulty=data["difficulty"],
            timestamp=data["timestamp"],
            nonce=data["nonce"],
            block_hash=data["hash"],
        )
